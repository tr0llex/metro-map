/**
 * Соседние пары станций линии — единственный правильный способ обойти линию.
 *
 * `line.stationIds` — это ПРИНАДЛЕЖНОСТЬ, а не маршрут. Ответвления лежат в
 * конце списка, поэтому обход подряд соединяет последнюю станцию основного хода
 * с первой станцией ветки. У Филёвской это давало штрих от «Александровского
 * сада» к «Деловому центру» — линию через полсхемы, которой не существует, —
 * и ту же ложную пару в метриках ритма станций.
 *
 * Функция живёт отдельно, потому что нужна и рантайму (отрисовка полилиний), и
 * анализатору качества. Раньше такой обход был скопирован в четырёх местах, и
 * поправить его пришлось бы во всех четырёх.
 */

/** Минимум, который нужен от линии: структурный тип, а не привязка к классу. */
type LineWithSegments = {
  stationIds: string[]
  segments?: string[][]
}

/**
 * Возвращает пары соседних станций. Для кольцевой линии добавляет замыкающую
 * пару «последняя → первая».
 *
 * `has` отсеивает станции без координат: пара строится только между теми, что
 * реально есть на схеме.
 */
export function lineStationPairs(
  line: LineWithSegments,
  isRing: boolean,
  has?: (id: string) => boolean,
): [string, string][] {
  // Данные, собранные до появления ответвлений, поля segments не имеют.
  const segments = line.segments?.length ? line.segments : [line.stationIds]
  const pairs: [string, string][] = []

  for (const segment of segments) {
    const ids = has ? segment.filter(has) : segment
    if (ids.length < 2) continue
    for (let i = 0; i < ids.length - 1; i += 1) pairs.push([ids[i], ids[i + 1]])
    // Замыкать в кольцо можно только основной ход: ответвлений у кольцевых
    // линий не бывает, но segments[0] и без них здесь единственный.
    if (isRing && segment === segments[0] && ids.length > 2) {
      pairs.push([ids[ids.length - 1], ids[0]])
    }
  }

  return pairs
}
