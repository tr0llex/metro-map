/**
 * Счётчики событий интерфейса.
 *
 * Зачем это здесь. Метро считает маршруты на клиенте и работает офлайн:
 * до сервера не доходит ничего, поэтому из журнала nginx нельзя узнать даже
 * того, строит ли кто-нибудь маршруты вообще. Просмотр страницы виден,
 * пользование — нет.
 *
 * Что уходит на сервер: пустой POST на /e/<имя события>. Ни тела, ни
 * параметров, ни cookie, ни идентификатора — ни сессии, ни посетителя.
 * Сервер отвечает 204 и пишет в журнал строку вида
 *
 *     metro.samoy.love "POST /e/route_built HTTP/2.0" 204 0 0.000
 *
 * IP и User-Agent в этом журнале отсутствуют физически: их нет в log_format.
 * Связать два события одного человека не по чему — пересекать нечего.
 *
 * Список имён закрыт и на сервере тоже (nginxlog.yml в metrics.samoy.love):
 * незнакомое имя сворачивается в один ряд "other". Добавляя событие здесь,
 * добавьте его и там, иначе оно потеряется среди чужих запросов.
 */

/** Единственный источник правды по именам. Тип не даст опечатке уехать. */
export const SITE_EVENTS = ['route_built', 'station_pick', 'pwa_install'] as const

export type SiteEvent = (typeof SITE_EVENTS)[number]

/**
 * Отправить событие. Никогда не бросает и ничего не возвращает: счётчик не
 * стоит того, чтобы из-за него сломался обработчик клика.
 *
 * sendBeacon, а не fetch: браузер доставляет его сам и переживает уход со
 * страницы, а обычный fetch при закрытии вкладки отменяется. Где beacon
 * недоступен — fetch с keepalive; где нет и его, событие просто теряется.
 */
export function trackEvent(event: SiteEvent): void {
  if (typeof navigator === 'undefined') return

  const url = `/e/${event}`

  try {
    if (typeof navigator.sendBeacon === 'function') {
      // Без второго аргумента: sendBeacon шлёт POST без тела и без
      // Content-Type. Строка или Blob добавили бы и то, и другое, а событие
      // целиком помещается в путь.
      navigator.sendBeacon(url)
      return
    }

    if (typeof fetch === 'function') {
      void fetch(url, { method: 'POST', keepalive: true }).catch(() => {})
    }
  } catch {
    // Блокировщик, офлайн, отключённая сеть — событие теряется молча.
    // Это счётчик, а не функциональность.
  }
}
